#!/usr/bin/env bash
# Phosphor installer for Debian/Ubuntu.
#
# Installs Docker Engine + the Compose plugin if not already present, picks
# host ports that aren't already in use (so it won't collide with anything
# else running on the box), writes infra/.env, and brings up the backend +
# web containers via `docker compose`.
#
# Usage: sudo ./install.sh [--api-port N] [--web-port N]
set -euo pipefail

APP_NAME="Phosphor"
INFRA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$INFRA_DIR/.env"
MANIFEST="$INFRA_DIR/.install-manifest"
DEFAULT_API_PORT=61337
DEFAULT_WEB_PORT=3100
WANT_API_PORT="$DEFAULT_API_PORT"
WANT_WEB_PORT="$DEFAULT_WEB_PORT"

log() { echo "[phosphor-install] $*"; }
die() { echo "[phosphor-install] ERROR: $*" >&2; exit 1; }

usage() {
  cat <<EOF
Usage: sudo $0 [--api-port N] [--web-port N]

  --api-port N   Preferred host port for the API (default: $DEFAULT_API_PORT).
                 If it's already in use, the next free port is picked instead.
  --web-port N   Preferred host port for the web app (default: $DEFAULT_WEB_PORT).
                 Same free-port fallback behavior.

Installs Docker if needed, then runs \`docker compose up -d --build\` for the
backend and web services (the optional Caddy reverse-proxy/HTTPS service is
left for you to start manually — see docs/deployment.md).
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --api-port) WANT_API_PORT="${2:?--api-port requires a value}"; shift 2 ;;
    --web-port) WANT_WEB_PORT="${2:?--web-port requires a value}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) die "Unknown argument: $1 (see --help)" ;;
  esac
done

require_root() {
  if [ "$(id -u)" -ne 0 ]; then
    die "Run this as root, e.g.: sudo $0"
  fi
}

check_os() {
  [ -f /etc/os-release ] || die "Cannot detect the OS (/etc/os-release is missing)."
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${ID:-}" in
    debian|ubuntu) ;;
    *)
      case " ${ID_LIKE:-} " in
        *" debian "*|*" ubuntu "*) ;;
        *) die "This installer supports Debian/Ubuntu only (detected: ${PRETTY_NAME:-unknown ID=$ID})." ;;
      esac
      ;;
  esac
  log "Detected OS: ${PRETTY_NAME:-$ID}"
}

install_docker() {
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    log "Docker + Compose plugin already installed ($(docker --version))."
    return
  fi
  log "Installing Docker Engine + Compose plugin from Docker's official apt repository..."
  apt-get update -y
  apt-get install -y ca-certificates curl gnupg
  install -m 0755 -d /etc/apt/keyrings
  # shellcheck disable=SC1091
  . /etc/os-release
  curl -fsSL "https://download.docker.com/linux/${ID}/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/${ID} ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  systemctl enable --now docker
  log "Docker installed: $(docker --version)"
}

# Returns 0 (true) if something is already listening on the given TCP port.
port_in_use() {
  local port="$1"
  if command -v ss >/dev/null 2>&1; then
    ss -Htln "sport = :${port}" 2>/dev/null | grep -q ":${port}[[:space:]]" && return 0
    return 1
  fi
  # Fallback with no extra tooling required: try to connect to it.
  if (exec 3<>"/dev/tcp/127.0.0.1/${port}") 2>/dev/null; then
    exec 3<&- 3>&-
    return 0
  fi
  return 1
}

# Prints the first free port at or after $1 (checked from the host, so this
# also catches ports used by software outside Docker entirely).
find_free_port() {
  local port="$1" tries=0
  while port_in_use "$port"; do
    tries=$((tries + 1))
    [ "$tries" -gt 100 ] && die "Could not find a free port starting from $1 after 100 attempts."
    port=$((port + 1))
  done
  echo "$port"
}

main() {
  require_root
  check_os
  install_docker

  log "Checking for available ports..."
  API_PORT="$(find_free_port "$WANT_API_PORT")"
  WEB_PORT="$(find_free_port "$WANT_WEB_PORT")"
  [ "$API_PORT" != "$WANT_API_PORT" ] && log "Port $WANT_API_PORT is taken — using $API_PORT for the API instead."
  [ "$WEB_PORT" != "$WANT_WEB_PORT" ] && log "Port $WANT_WEB_PORT is taken — using $WEB_PORT for the web app instead."

  local jwt_secret lan_ip api_base_url
  jwt_secret="$(openssl rand -hex 32 2>/dev/null || head -c32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  lan_ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
  api_base_url="http://${lan_ip:-localhost}:${API_PORT}"

  cat > "$ENV_FILE" <<EOF
# Generated by install.sh on $(date -u +%FT%TZ). Safe to hand-edit;
# re-run install.sh (or just \`docker compose up -d\`) to reapply.
JWT_SECRET=${jwt_secret}
API_BASE_URL=${api_base_url}
CORS_ORIGINS=*
ADMIN_EMAIL=
API_PORT=${API_PORT}
WEB_PORT=${WEB_PORT}
EOF

  cat > "$MANIFEST" <<EOF
# Recorded by install.sh; read by uninstall.sh. Do not edit by hand.
INFRA_DIR=${INFRA_DIR}
API_PORT=${API_PORT}
WEB_PORT=${WEB_PORT}
INSTALLED_AT=$(date -u +%FT%TZ)
EOF

  log "Building and starting the backend + web containers (first build can take a few minutes)..."
  (cd "$INFRA_DIR" && docker compose --env-file "$ENV_FILE" up -d --build backend web)

  cat <<EOF

${APP_NAME} is up.
  Web:  http://${lan_ip:-localhost}:${WEB_PORT}
  API:  ${api_base_url}

Sign up at the web address above — the first account becomes admin.

For HTTPS via the bundled Caddy reverse proxy, see docs/deployment.md and
then run: docker compose --env-file "$ENV_FILE" up -d proxy

To uninstall: sudo ./uninstall.sh
EOF
}

main "$@"
