import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import vm from "node:vm";
import { afterEach, expect, it } from "vitest";
const folders: string[] = [];
afterEach(() => folders.splice(0).forEach(folder => fs.rmSync(folder, { recursive: true, force: true })));
it("opens and closes only the bundled listener while retaining authentication and download settings", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "bundled-qbit-startup-")); folders.push(root);
  const source = fs.readFileSync(path.resolve(__dirname, "../../infra/single-container/start.cjs"), "utf8");
  const context = vm.createContext({ fs, path, crypto, root, configRoot: root, process: { env: {} }, secret: () => "fixture-password" });
  vm.runInContext(source.slice(source.indexOf("function ini("), source.indexOf("function proxy(")), context);
  const prepare = (host = "") => vm.runInContext(`prepareQbit(${JSON.stringify(host)})`, context);
  const file = path.join(root, "qbittorrent/qBittorrent/config/qBittorrent.conf");
  prepare();
  expect(fs.readFileSync(file, "utf8")).toContain("WebUI\\Address=127.0.0.1");
  prepare("streamrd-fixture");
  let config = fs.readFileSync(file, "utf8");
  expect(config).toContain("WebUI\\Address=0.0.0.0");
  expect(config).toContain("WebUI\\ServerDomains=127.0.0.1;localhost;streamrd-fixture");
  for (const expected of ["WebUI\\LocalHostAuth=true", "WebUI\\HostHeaderValidation=true", "WebUI\\AuthSubnetWhitelistEnabled=false", "Session\\DefaultSavePath=", "Session\\Port=6881", "WebUI\\Password_PBKDF2="]) expect(config).toContain(expected);
  expect(fs.statSync(file).mode & 0o777).toBe(0o600);
  prepare(); config = fs.readFileSync(file, "utf8");
  expect(config).toContain("WebUI\\Address=127.0.0.1");
  expect(config).not.toContain("streamrd-fixture");
  expect(config).toContain("WebUI\\LocalHostAuth=true");
});
